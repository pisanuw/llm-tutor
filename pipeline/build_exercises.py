"""Build the curated exercise bank (Session 18, S28).

`curriculum/exercises.json` is the runtime source of practice exercises. It is
*curated data*, not a regex scrape computed at request time: every exercise has
a stable id, a full prompt, explicit goal ids, a difficulty, optional starter
code, and an expected_behavior string the evaluator can use.

Why goal-derived rather than scraped
------------------------------------
The original bank scraped "Student Interaction" blocks out of the lecture
`script.md` files. Those scripts are gitignored (regenerated by the pipeline)
and are absent in deploy/dev checkouts, so the scrape yields nothing at runtime;
the audit (finding S28) also judged the scraped prompts too weak to anchor
drill/exam modality or per-goal mastery. The learning goals, by contrast,
are audited (Session 12), anchored (Session 13), checked into git, and already
carry a precise course + lecture + title + description. Deriving exercises from
them gives every exercise an exact goal id by construction, which is exactly what
per-goal mastery (S9/S10) and `get_exercise(goal_id=...)` need.

Usage
-----
    python -m pipeline build-exercises            # write curriculum/exercises.json
    python -m pipeline build-exercises --dry-run  # print summary only

Code exercises are built only when courses.yaml sets ``code_language`` (in
that language; starter code only for C++, the one language the sandbox
runs). Without it, a goal whose verb asks the student to produce something
gets a worked problem (a "trace" exercise) instead.

The app's old regex scraper of `script.md` (a runtime fallback when this file
was missing) was removed in plan step 5.7; this build is the only importer. An offline LLM cleanup pass (polish prompts, tighten
expected_behavior, add starter code) is a documented follow-up: it would read
this file, refine each entry with the local `claude` CLI, and write it back. The
deterministic build here is the reproducible seed that pass would start from.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

import click
from rich.console import Console
from tutor.courses import IDENTITY
from tutor.paths import CURRICULUM_DIR

ROOT = Path(__file__).parent.parent
GOALS_PATH = CURRICULUM_DIR / "learning_goals.json"
EXERCISES_PATH = CURRICULUM_DIR / "exercises.json"

console = Console()


# ---------------------------------------------------------------------------
# Difficulty inference
# ---------------------------------------------------------------------------

# Difficulty is keyed off the title's *leading verb* (the titles are imperative
# phrases: "Compute a star's distance from its parallax", "Trace the Moon's
# orbit through a month"). Substring matching over the whole title was too
# noisy: a word like "code" matched "decoding", and "Explain why the sky is
# blue" read as a production task. The leading verb is the reliable signal for
# what the student actually does. A verb in neither set yields a concept-only
# goal (Explain, Compare, Identify, Choose, State, Define, Use, ...).

# Leading verbs where the student produces something: code when the course
# uses code (``code_language``), a worked solution otherwise.
_CODE_VERBS = frozenset({
    "implement", "write", "apply", "solve", "convert", "traverse", "overload",
    "declare", "allocate", "split", "manage", "insert", "iterate", "simplify",
    "replace", "resolve", "add",
})

# Leading verbs where the student works an example by hand (trace, prove,
# derive, draw, fill a table, classify a growth rate).
_TRACE_VERBS = frozenset({
    "trace", "traceback", "construct", "classify", "compute", "derive",
    "verify", "carry", "prove", "negate", "predict", "draw", "analyze",
    "build", "fill", "evaluate",
})


def _leading_verb(title: str) -> str:
    """First word of the title, lowercased, stripped of trailing punctuation."""
    first = title.split()[0] if title.split() else ""
    return first.strip(",.:;").lower()


def _goal_phrase(description: str) -> str:
    """Turn 'Student can <verb phrase>.' into the bare '<verb phrase>'."""
    desc = description.strip()
    desc = re.sub(r"^(The student can |Student can |The student |Student )", "", desc)
    return desc.rstrip(".")


def _lower_first(text: str) -> str:
    return text[:1].lower() + text[1:] if text else text


# ---------------------------------------------------------------------------
# Per-difficulty exercise templates
# ---------------------------------------------------------------------------

def _starter_code(title: str, phrase: str) -> str:
    """A compilable skeleton when the course's language is C++ (the one the
    sandbox runs); no starter for any other language."""
    if IDENTITY.code_language.strip().lower() not in ("c++", "cpp"):
        return ""
    return (
        f"// {title}\n"
        f"// Goal: {phrase}.\n"
        "#include <iostream>\n"
        "using namespace std;\n\n"
        "int main() {\n"
        "    // TODO: write and test your solution here\n"
        "    return 0;\n"
        "}\n"
    )


def _exercises_for_goal(goal: dict) -> list[dict]:
    gid = goal["id"]
    course = goal["course"]
    lecture = goal["lecture"]
    title = goal["title"]
    title_lc = _lower_first(title)
    desc = goal["description"].strip()
    phrase = _goal_phrase(desc)
    hook = goal.get("hook", "").strip()

    out: list[dict] = []

    def add(difficulty: str, prompt: str, expected: str, starter: str = "") -> None:
        out.append({
            "id": f"{gid}-{difficulty}",
            "course": course,
            "lecture_num": lecture,
            "topic": title,
            "difficulty": difficulty,
            "prompt": " ".join(prompt.split()),
            "hints": [],
            "expected_behavior": " ".join(expected.split()),
            "starter_code": starter,
            "goal_ids": [gid],
        })

    # Concept: always. Elicits an explanation in the student's own words.
    concept_hook = f" {hook}" if hook else ""
    add(
        "concept",
        f"In your own words, explain how to {phrase}.{concept_hook} "
        f"Walk a classmate through the core idea and one short example.",
        f"A clear explanation, in the student's own words, showing they can "
        f"{phrase}, including at least one correct concrete example.",
    )

    verb = _leading_verb(title)
    lang = IDENTITY.code_language

    # Code: when the goal reads as producing code and the course uses code.
    if verb in _CODE_VERBS and lang:
        add(
            "code",
            f"Write {lang} that demonstrates how to {title_lc}. Concretely: {desc} "
            f"Aim for clean, idiomatic {lang} that runs and handles the "
            f"obvious edge cases.",
            f"A {lang} solution that lets the student {phrase}. It should run "
            f"cleanly, produce correct output on representative inputs, and "
            f"handle the obvious edge cases.",
            starter=_starter_code(title, phrase),
        )
    # Without code, the same goal is a problem worked on paper.
    elif verb in _CODE_VERBS:
        add(
            "trace",
            f"Work a short problem that shows how to {title_lc}. Concretely: {desc} "
            f"Set it up, show each step of your work, and state the result.",
            f"A correct worked solution showing the student can {phrase}, with the "
            f"setup, each step, and the right result.",
        )

    # Trace: when the goal reads as working an example by hand.
    if verb in _TRACE_VERBS:
        add(
            "trace",
            f"Trace through {title_lc} by hand on a small example. Show each step "
            f"of your reasoning (what changes at each step and why) and state "
            f"the final result.",
            f"A correct step-by-step trace demonstrating how to {phrase}, with the "
            f"right final result and the reasoning shown at each step.",
        )

    return out


# ---------------------------------------------------------------------------
# Build
# ---------------------------------------------------------------------------

def build_bank(goals: list[dict]) -> list[dict]:
    bank: list[dict] = []
    for goal in goals:
        bank.extend(_exercises_for_goal(goal))
    bank.sort(key=lambda e: e["id"])
    return bank


@click.command("build-exercises")
@click.option("--dry-run", is_flag=True, help="Print a summary, do not write the file.")
def build_exercises(dry_run: bool) -> None:
    data = json.loads(GOALS_PATH.read_text())
    goals = data["goals"]
    graph_version = data.get("graph_version", 0)

    bank = build_bank(goals)

    ids = [e["id"] for e in bank]
    assert len(ids) == len(set(ids)), "duplicate exercise ids"
    assert all(e["goal_ids"] for e in bank), "every exercise needs >= 1 goal id"
    assert all(e["expected_behavior"] for e in bank), "every exercise needs expected_behavior"

    by_course = Counter(e["course"] for e in bank)
    by_diff = Counter(e["difficulty"] for e in bank)

    console.print(f"[bold]Built {len(bank)} exercises[/bold] from {len(goals)} goals")
    console.print(f"  by course:     {dict(by_course)}")
    console.print(f"  by difficulty: {dict(by_diff)}")
    console.print(f"  goals covered: {len({g for e in bank for g in e['goal_ids']})}/{len(goals)}")

    if dry_run:
        console.print("[yellow]--dry-run: not written[/yellow]")
        return

    out = {
        "graph_version": graph_version,
        "generated_from": "learning_goals.json",
        "exercises": bank,
    }
    EXERCISES_PATH.write_text(json.dumps(out, indent=2) + "\n")
    console.print(f"[green]Wrote {EXERCISES_PATH.relative_to(ROOT)}[/green]")


if __name__ == "__main__":
    build_exercises()
